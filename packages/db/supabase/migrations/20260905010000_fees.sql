  razorpay_payment_id text,
  status text not null default 'recorded' check (status in ('recorded', 'pending_gateway', 'captured', 'failed')),
  receipt_number text,
  received_by_auth_user_id uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  constraint payment_online_starts_pending_gateway check (
