-- For a recurring head, amount_paise IS the per-month amount -- no annual-to-monthly split or
-- rounding-remainder math anywhere, the school configures the monthly rate directly (matches how
-- they already think about it, and sidesteps a whole class of paise-rounding bugs). For a
-- one-time head, due once, at one_time_installment_number.
create table public.fee_structure_item (
  id uuid primary key default gen_random_uuid(),
  fee_structure_id uuid not null references public.fee_structure(id) on delete cascade,
  fee_head_id uuid not null references public.fee_head(id) on delete cascade,
  amount_paise bigint not null check (amount_paise >= 0),
  one_time_installment_number int check (one_time_installment_number between 1 and 12),
  unique (fee_structure_id, fee_head_id)
);
alter table public.fee_structure_item enable row level security;

-- A plain CHECK can't reference fee_head.is_recurring (a different table), hence a trigger:
-- a recurring head must NOT carry a one-time installment number (it's due every month by
-- definition) and a one-time head MUST carry one (otherwise fn_generate_yearly_invoices has no
-- installment to attach it to and it would silently never appear on any invoice).
create or replace function public.fn_validate_fee_structure_item()
returns trigger
language plpgsql
as $$
declare
  v_is_recurring boolean;
begin
  select is_recurring into v_is_recurring from public.fee_head where id = new.fee_head_id;
  if v_is_recurring and new.one_time_installment_number is not null then
    raise exception 'fee_head % is recurring -- one_time_installment_number must be null', new.fee_head_id;
  end if;
  if not v_is_recurring and new.one_time_installment_number is null then
    raise exception 'fee_head % is one-time -- one_time_installment_number is required', new.fee_head_id;
  end if;
  return new;
end;
$$;

create trigger trg_fee_structure_item_validate
  before insert or update on public.fee_structure_item
  for each row execute function public.fn_validate_fee_structure_item();

