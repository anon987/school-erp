-- IMMUTABLE: insert + select only, no update/delete grant to `authenticated` at all (see the
-- grants below) -- this is the database-level enforcement of CLAUDE.md's "payment records are
-- immutable," not just a convention. The one narrow exception -- an online payment's status
-- moving from 'pending_gateway' to 'captured'/'failed' once Razorpay's webhook confirms it -- is
-- not a correction of a completed transaction, it's that transaction completing for the first
