-- ---------------------------------------------------------------------------
-- Invoice status maintenance: recomputed from payment/payment_adjustment/fine activity, never
-- hand-set by the app (the app sets it only implicitly, by inserting rows this trigger reacts
-- to). "Paid amount" = recorded/captured payments minus refunds; fines add to what's owed.
-- ---------------------------------------------------------------------------
create or replace function public.fn_recompute_invoice_status(p_invoice_id uuid)
returns void
language plpgsql
as $$
declare
  v_total bigint;
  v_current_status text;
  v_paid bigint;
  v_fines bigint;
  v_refunded bigint;
  v_owed bigint;
begin
  select total_amount_paise, status into v_total, v_current_status from public.invoice where id = p_invoice_id;
  if v_current_status = 'cancelled' then
    return;
  end if;

  select coalesce(sum(amount_paise), 0) into v_paid
    from public.payment where invoice_id = p_invoice_id and status in ('recorded', 'captured');
  select coalesce(sum(amount_paise), 0) into v_fines
    from public.fine where invoice_id = p_invoice_id;
  select coalesce(sum(amount_paise), 0) into v_refunded
    from public.payment_adjustment where invoice_id = p_invoice_id and type in ('refund', 'concession_adjustment', 'fine_waiver');
  -- 'correction' adjustments are deliberately excluded from this sum: amount_paise has no sign
  -- (always positive, per its check constraint), so a correction has no well-defined direction to
  -- apply automatically. They're recorded for audit/reference; a genuine invoice-total fix goes
  -- through cancelling and reissuing the invoice, not a silent auto-adjustment here.

  v_owed := v_total + v_fines - v_refunded;

  update public.invoice
  set status = case
    when v_paid <= 0 then 'pending'
    when v_paid < v_owed then 'partially_paid'
    else 'paid'
  end
  where id = p_invoice_id;
end;
$$;

create or replace function public.fn_trg_recompute_invoice_status()
returns trigger
language plpgsql
as $$
begin
  perform public.fn_recompute_invoice_status(coalesce(new.invoice_id, old.invoice_id));
  return null;
end;
$$;

create trigger trg_payment_recompute_invoice_status
